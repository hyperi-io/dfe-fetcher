// Object-store source family -- S3 backend live; GCS/Azure Blob Phase 2 stubs
// =============================================================================
//
// S3 tests use the existing AWS test credentials (.env-cloud AWS_*). To
// target a specific test bucket, set OBJECT_STORE_S3_BUCKET +
// OBJECT_STORE_S3_PREFIX (defaults pick the existing ESH_S3_BUCKET with
// an empty prefix).

fn object_store_s3_config() -> S3BackendConfig {
    S3BackendConfig {
        region: optional("OBJECT_STORE_S3_REGION")
            .or_else(|| optional("AWS_REGION"))
            .unwrap_or_else(|| "us-west-2".into()),
        endpoint_override: optional("OBJECT_STORE_S3_ENDPOINT"),
        access_key_id: Some(require("AWS_ACCESS_KEY_ID")),
        secret_access_key: Some(require("AWS_SECRET_ACCESS_KEY").into()),
        credential_secret: None,
        buckets: vec![],
    }
}

#[tokio::test]
#[ignore = "requires live AWS credentials + an S3 bucket the fetcher SA can list"]
async fn object_store_s3_list_only() {
    load_env();
    let bucket = optional("OBJECT_STORE_S3_BUCKET")
        .or_else(|| optional("ESH_S3_BUCKET"))
        .expect("set OBJECT_STORE_S3_BUCKET or ESH_S3_BUCKET in .env-cloud");
    let prefix = optional("OBJECT_STORE_S3_PREFIX").unwrap_or_default();

    let mut s3 = object_store_s3_config();
    s3.buckets = vec![ObjectStoreBucket {
        bucket: bucket.clone(),
        prefixes: vec![ObjectStorePrefix {
            prefix: prefix.clone(),
            format: ObjectStoreFormat::Jsonl,
            source_tag: "smoke_test".to_string(),
            topic: None,
        }],
    }];

    let cfg = ObjectStoreSourceConfig {
        enabled: true,
        backends: vec![ObjectStoreBackendConfig::S3(s3)],
        interval_secs: None,
        topic: "test-object_store".to_string(),
        filter: None,
    };
    let src = ObjectStoreSource::new(cfg);
    // Empty bucket -> Ok(vec![]) is a valid outcome. We just want to
    // assert the list call signs + executes without error.
    let results = src.fetch(None).await.expect("object_store fetch errored");
    let total: usize = results.iter().map(|r| r.records.len()).sum();
    eprintln!(
        "object_store s3({bucket}/{prefix}): {} FetchResult(s), {total} record(s) total",
        results.len(),
    );
}

#[tokio::test]
#[ignore = "requires AWS credentials AND an S3 prefix with at least one gzipped JSON-lines object"]
async fn object_store_s3_parse_json_gz_objects() {
    load_env();
    let bucket = require("OBJECT_STORE_S3_BUCKET");
    let prefix = require("OBJECT_STORE_S3_PREFIX");

    let mut s3 = object_store_s3_config();
    s3.buckets = vec![ObjectStoreBucket {
        bucket: bucket.clone(),
        prefixes: vec![ObjectStorePrefix {
            prefix: prefix.clone(),
            format: ObjectStoreFormat::JsonGz,
            source_tag: "smoke_test_json_gz".to_string(),
            topic: None,
        }],
    }];
    let cfg = ObjectStoreSourceConfig {
        enabled: true,
        backends: vec![ObjectStoreBackendConfig::S3(s3)],
        interval_secs: None,
        topic: "test-object_store".to_string(),
        filter: None,
    };
    let src = ObjectStoreSource::new(cfg);
    let results = src.fetch(None).await.expect("object_store fetch errored");
    let total: usize = results.iter().map(|r| r.records.len()).sum();
    eprintln!(
        "object_store s3({bucket}/{prefix}) json_gz: {} FetchResult(s), {total} record(s) total",
        results.len(),
    );
    for r in &results {
        assert!(
            r.source.starts_with("object_store."),
            "unexpected source tag: {}",
            r.source
        );
        for rec in &r.records {
            let parsed: serde_json::Value =
                serde_json::from_slice(rec).expect("each emitted record must be valid JSON");
            // Every record carries the envelope; the bucket name is the
            // ground truth we asserted on.
            assert_eq!(parsed["_dfe_fetcher_object"]["bucket"], bucket.as_str());
        }
    }
}

