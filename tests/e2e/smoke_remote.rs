//! Live remote-source smoke tests against real tenants / SaaS accounts.
//!
//! Covers AWS, Azure, M365, GCP (cloud APIs) plus GitHub audit (SaaS). All
//! tests are `#[ignore]`d so they don't run on every push. To run them:
//!
//! ```bash
//! cargo nextest run --test e2e -- --ignored
//! # or filter to one source family:
//! cargo nextest run --test e2e -- --ignored github_
//! ```
//!
//! Credentials are loaded from `.env-cloud` (canonical, generated by
//! `infra/test/gen-env.py` from `kv/dfe-test/*`) with a fallback to `.env`.
//! Each test panics with a clear message if its required env vars are
//! missing -- no more silent skips that pretend to pass.
//!
//! ## Credential reuse
//!
//! `.env-cloud` does not carry separate `M365_*` variables. M365 IS Entra/
//! Azure AD: the `dfe-fetcher-azure-test` SP in the HyperI MS tenant has
//! both Azure Management and Microsoft Graph permissions granted, so the
//! M365 tests reuse `AZURE_TENANT_ID`/`AZURE_CLIENT_ID`/`AZURE_CLIENT_SECRET`.
//!
//! ## Per-service isolation
//!
//! Each test exercises ONE service (`Source::fetch` aggregates across all
//! configured services and swallows errors, which previously masked broken
//! services as "passing"). Coverage is per-service so a regression in one
//! surface fails its own test.

