// =============================================================================
// AWS -- SigV4 against real CloudTrail / CloudWatch, through the shipped
// `aws` profile the typed `sources.aws` block maps onto. Each unit is
// fetched off the shape as the driver would, so a refusal fails its own
// test instead of being swallowed.
// =============================================================================

fn aws_base() -> AwsSourceConfig {
    AwsSourceConfig {
        enabled: true,
        region: optional("AWS_REGION").unwrap_or_else(|| "ap-southeast-2".to_string()),
        access_key_id: Some(require("AWS_ACCESS_KEY_ID")),
        secret_access_key: Some(require("AWS_SECRET_ACCESS_KEY").into()),
        assume_role_arn: None,
        credential_secret: None,
        endpoint_override: None,
        interval_secs: None,
        services: vec![],
        connections: vec![],
        topic: "test-aws".to_string(),
        filter: None,
    }
}

/// One unit of the aws block as the profile fetches it, with the record
/// count printed.
async fn aws_fetch(
    unit: &str,
    config: HashMap<String, serde_json::Value>,
) -> Vec<serde_json::Value> {
    load_env();
    let mut cfg = aws_base();
    cfg.services.push(AwsService {
        name: unit.to_string(),
        config,
    });
    let shape = builtin_shape(cfg.instances().expect("aws block maps"));
    assert_eq!(
        format!("{}.{unit}", shape.connection_id()),
        format!("aws.{unit}")
    );
    let rows = shape_rows(&shape, unit)
        .await
        .unwrap_or_else(|e| panic!("AWS {unit} fetch failed: {e}"));
    eprintln!("AWS {unit}: {} record(s)", rows.len());
    rows
}

