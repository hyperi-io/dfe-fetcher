/// The queue shape the block maps onto: the shipped `gcp_pubsub` profile
/// bound to the block's instance.
fn pubsub_shape(cfg: &GcpPubsubSourceConfig) -> dfe_fetcher_rest::shape::queue::QueueShape {
    let [built] = <[dfe_fetcher::config::BuiltinInstance; 1]>::try_from(
        cfg.instances().expect("gcp_pubsub block maps"),
    )
    .unwrap_or_else(|v| panic!("one connection, got {}", v.len()));
    let profile = dfe_fetcher_rest::profile::bound::resolve_profile(
        &built.instance,
        dfe_fetcher::profiles::shipped(),
    )
    .expect("a shipped profile");
    dfe_fetcher_rest::shape::RestShape::from_instance(
        &profile,
        &built.instance,
        &built.connection_id,
        dfe_fetcher_rest::http_client().expect("http client"),
        &dfe_fetcher_rest::exchange_client().expect("exchange client"),
    )
    .and_then(dfe_fetcher_rest::shape::queue::QueueShape::new)
    .unwrap_or_else(|e| panic!("bind {}: {e}", built.connection_id))
}

